using System.Text;
using Novolis.Documents;
using Novolis.Documents.Skia;

var outDir = Path.GetFullPath(Path.Combine(
    Environment.GetFolderPath(Environment.SpecialFolder.UserProfile),
    ".novolis",
    "artifacts",
    "hello-document"));
Directory.CreateDirectory(outDir);
var pdfPath = Path.Combine(outDir, "hello-document.pdf");

static string Lorem(int words)
{
    ReadOnlySpan<string> corpus =
    [
        "the", "river", "ran", "cold", "through", "Duckville", "harbor", "lights", "winked", "across",
        "the", "strait", "while", "freight", "bells", "marked", "the", "hour", "and", "spray", "bit",
        "the", "quay", "stones", "Captain", "Rook", "checked", "the", "manifest", "twice", "then",
        "folded", "the", "chart", "into", "his", "coat", "as", "fog", "settled", "low", "over",
        "the", "channel", "markers", "and", "the", "tide", "turned", "toward", "the", "open", "reach",
    ];
    var parts = new string[words];
    for (var i = 0; i < words; i++)
        parts[i] = corpus[i % corpus.Length];
    var text = string.Join(' ', parts);
    return char.ToUpperInvariant(text[0]) + text[1..] + ".";
}

var document = Document.Create("Duckville Harbor")
    .Meta(m => m
        .Subtitle("A NearSol Freighter Chronicle")
        .Series("Calypso Tramp Stories")
        .Author("Novolis")
        .Publisher("Novolis-Platform")
        .Subject("Tramp freighter fiction")
        .Keywords("calypso", "harbor", "nearSol")
        .Language("en")
        .Version("1.0")
        .Date(new DateOnly(2026, 8, 8))
        .Rights("© 2026 Novolis-Platform. All rights reserved."))
    .Page(p => p
        .Trade6x9()
        .Header(h => h
            .Template("{title}")
            .FontSize(9f)
            .IncludeBody()
            .UseChapterTitle())
        .Footer(f => f
            .Template("{page} / {pages}")
            .FontSize(9f)
            .IncludeFirstPage()
            .IncludeToc()
            .IncludeBody()
            .IncludeLastPage()))
    .Watermark(w => w.Text("SAMPLE").Color(DocumentColor.Red).Opacity(0.10f).On(WatermarkPages.All))
    .Body(b => b
        .First(f => f.Lines("Trade paperback sample", "Printed via Novolis.Documents.Skia"))
        .Content(c => c
            .Toc()
            .Chapter("Chapter 1 - Arrival", ch => ch
                .Paragraph(Lorem(180))
                .H2("Quay-side")
                .Paragraph(Lorem(120))
                .Table(t => t
                    .Headers("Cargo", "Tons", "Bond")
                    .Row("Grain", "120", "Yes")
                    .Row("Timber", "80", "No")
                    .Row("Ore", "45", "Yes")
                    .Rules(TableRuleStyle.Horizontal)
                    .HeaderBackground())
                .SceneBreak()
                .Paragraph(Lorem(100)))
            .Chapter("Chapter 2 - Manifest", ch => ch
                .Paragraph(Lorem(80))
                .H2("Bonded cargo")
                .Paragraph("The bonded list runs long enough to prove table page breaks with a repeated header.")
                .Table(t => t
                    .Headers("#", "Cargo", "Tons", "Bond")
                    .Rows(Enumerable.Range(1, 48).Select(i => (IReadOnlyList<string>)
                    [
                        $"{i}",
                        i % 3 == 0 ? "Grain" : i % 3 == 1 ? "Timber" : "Ore",
                        $"{10 + (i % 9) * 5}",
                        i % 2 == 0 ? "Yes" : "No",
                    ]))
                    .ColumnWidths(0.1f, 0.45f, 0.2f, 0.25f)
                    .Align(CellAlign.Left, CellAlign.Left, CellAlign.Right, CellAlign.Center)
                    .Rules(TableRuleStyle.Horizontal)
                    .HeaderBackground()
                    .RepeatHeaderOnPageBreak())
                .Paragraph(Lorem(60)))
            .Chapter("Chapter 3 - Departure", ch => ch
                .Paragraph(Lorem(180))))
        .Last(l => l
            .Title("Colophon")
            .Lines(
                "End of sample.",
                "Generated by Novolis.Documents.Skia for dogfood verification.")
            .Blocks(blocks => blocks.Table(t => t
                .Headers("Item", "Value")
                .Row("Engine", "Documents.Skia")
                .Row("Trim", "6×9 in")
                .Row("Margins", "print (0.75 / 0.5 / 0.5 / 0.65)")
                .Rules(TableRuleStyle.Horizontal)
                .HeaderBackground()))))
    .Build();

DocumentPdf.Write(document, pdfPath);
var bytes = File.ReadAllBytes(pdfPath);
var ascii = Encoding.ASCII.GetString(bytes);
var pageMarkers = 0;
for (var i = 0; i < ascii.Length - 10; i++)
{
    if (ascii.AsSpan(i).StartsWith("/Type /Page", StringComparison.Ordinal)
        && !ascii.AsSpan(i).StartsWith("/Type /Pages", StringComparison.Ordinal))
        pageMarkers++;
}

Console.WriteLine(pdfPath);
Console.WriteLine($"Bytes: {bytes.Length}");
Console.WriteLine($"PDF /Type /Page markers: {pageMarkers}");
return pageMarkers >= 5 && bytes.Length < 80_000 ? 0 : 1;
