using System.Globalization;
using System.Text;

namespace MobilityLab.Experiment;

static class MarkdownReport
{
    public static string Build(ExperimentResult result, TaxMobilityWorld.Model model, TimeSpan? elapsed = null)
    {
        var inv = CultureInfo.InvariantCulture;
        var sb = new StringBuilder();
        var months = model.History.Months;
        var e = result.Effects;
        var id = result.Identification;

        sb.AppendLine("# MobilityLab evidence report (single arm)");
        sb.AppendLine();
        AppendSpec(sb, result.Spec, result.SampleCount, elapsed, inv);
        sb.AppendLine("## Effect sizes");
        sb.AppendLine();
        sb.AppendLine("| Estimand | Value |");
        sb.AppendLine("|----------|-------|");
        sb.AppendLine($"| ATT Alpha pop | {e.AttAlphaPop.ToString("+0;-0", inv)} ({e.AttAlphaPopPct.ToString("+0.0%;-0.0%", inv)}) |");
        sb.AppendLine($"| DID pop growth | {e.DidPopGrowth.ToString("+0.0%;-0.0%", inv)} |");
        sb.AppendLine($"| ATT mean push | {e.AttMeanPush.ToString("+0.000;-0.000", inv)} |");
        sb.AppendLine($"| ATT cum tax revenue | {e.AttCumTaxRevenue.ToString("+0.0;-0.0", inv)} |");
        sb.AppendLine($"| ATT mean production | {e.AttMeanProduction.ToString("+0.00;-0.00", inv)} |");
        sb.AppendLine($"| Gamma absorb share | {e.GammaAbsorbShare.ToString("0.0%", inv)} |");
        if (e.HasEventStudy)
        {
            sb.AppendLine($"| Pre-shock DID | {e.PreShockDidGrowth.ToString("+0.0%;-0.0%", inv)} |");
            sb.AppendLine($"| Pre/post mean net mig | {e.PreShockMeanNetMig.ToString("0", inv)} / {e.PostShockMeanNetMig.ToString("0", inv)} |");
        }

        sb.AppendLine();
        sb.AppendLine("## Coupling checks");
        sb.AppendLine();
        sb.AppendLine($"**Result: {result.PassCount}/{result.CheckCount} {(result.AllPass ? "PASS" : "MIXED")}**");
        sb.AppendLine();
        sb.AppendLine("| Status | Claim | Detail |");
        sb.AppendLine("|--------|-------|--------|");
        foreach (var c in result.Checks)
            sb.AppendLine($"| {(c.Pass ? "PASS" : "FAIL")} | {Ascii(c.Claim)} | {Ascii(c.Detail)} |");
        sb.AppendLine();
        AppendSeries(sb, months, inv);
        sb.AppendLine("---");
        sb.AppendLine("*Generated by MobilityLab - paste this block into chat for review.*");
        return sb.ToString();
    }

    public static string BuildBattery(BatteryResult battery, TimeSpan? elapsed = null)
    {
        var inv = CultureInfo.InvariantCulture;
        var sb = new StringBuilder();
        var study = battery.Study;
        var primary = battery.Primary.Result;
        var e = primary.Effects;
        var agg = battery.Aggregates;
        var months = battery.Primary.Model.History.Months;

        sb.AppendLine("# MobilityLab science battery report");
        sb.AppendLine();
        sb.AppendLine("## Study spec");
        sb.AppendLine();
        sb.AppendLine("| Parameter | Value |");
        sb.AppendLine("|-----------|-------|");
        sb.AppendLine($"| Months | {study.Months} |");
        sb.AppendLine($"| Alpha treatment tax | {study.AlphaTax.ToString("0.00", inv)} |");
        sb.AppendLine($"| Beta / Gamma tax | {study.BetaTax.ToString("0.00", inv)} / {study.GammaTax.ToString("0.00", inv)} |");
        sb.AppendLine($"| Baseline / shock month | {study.BaselineMonths} / {study.ShockMonth} |");
        sb.AppendLine($"| Seeds | {string.Join(", ", study.Seeds)} |");
        sb.AppendLine($"| Dose grid | {(study.IncludeDose ? string.Join(", ", study.DoseGrid.Select(t => t.ToString("0.00", inv))) : "off")} |");
        sb.AppendLine($"| Placebo high twin | {study.IncludePlacebo} |");
        sb.AppendLine($"| Ensemble | {study.IncludeEnsemble} |");
        sb.AppendLine($"| War / agents | {study.WarShockOn} / {study.AgentsEnabled} |");
        if (elapsed is { } t)
            sb.AppendLine($"| Elapsed | {t.TotalSeconds.ToString("0.00", inv)}s |");
        sb.AppendLine();

        sb.AppendLine("## Research design");
        sb.AppendLine();
        sb.AppendLine(
            "Battery: primary shock/treatment vs same-seed CF (Alpha tax = Beta tax); " +
            "dose-response grid; high-tax placebo twin (Alpha=Beta=treatment); multi-seed ensemble. " +
            "Kernel Wave 2 (unrest/HD) is out of scope - this harness explores the Wave 1 policy surface.");
        sb.AppendLine();

        sb.AppendLine("## Study checks");
        sb.AppendLine();
        sb.AppendLine($"**Result: {battery.PassCount}/{battery.CheckCount} {(battery.AllPass ? "PASS" : "MIXED")}**");
        sb.AppendLine();
        sb.AppendLine("| Status | Claim | Detail |");
        sb.AppendLine("|--------|-------|--------|");
        foreach (var c in battery.StudyChecks)
            sb.AppendLine($"| {(c.Pass ? "PASS" : "FAIL")} | {Ascii(c.Claim)} | {Ascii(c.Detail)} |");
        sb.AppendLine();

        sb.AppendLine("## Primary effect sizes");
        sb.AppendLine();
        sb.AppendLine("| Estimand | Value | Notes |");
        sb.AppendLine("|----------|-------|-------|");
        sb.AppendLine(
            $"| ATT Alpha population | {e.AttAlphaPop.ToString("+0;-0", inv)} " +
            $"({e.AttAlphaPopPct.ToString("+0.0%;-0.0%", inv)}) | vs CF end {e.CounterfactualAlphaPopEnd.ToString("0", inv)} |");
        sb.AppendLine($"| Twin DID pop growth | {e.DidPopGrowth.ToString("+0.0%;-0.0%", inv)} | within primary |");
        sb.AppendLine($"| ATT mean push | {e.AttMeanPush.ToString("+0.000;-0.000", inv)} | post burn-in |");
        sb.AppendLine($"| ATT cum tax revenue | {e.AttCumTaxRevenue.ToString("+0.0;-0.0", inv)} | fiscal |");
        sb.AppendLine($"| ATT mean production | {e.AttMeanProduction.ToString("+0.00;-0.00", inv)} | economy |");
        sb.AppendLine($"| ATT end state cash | {e.AttEndStateCash.ToString("+0.0;-0.0", inv)} | |");
        sb.AppendLine($"| Gamma absorb share | {e.GammaAbsorbShare.ToString("0.0%", inv)} | |");
        sb.AppendLine($"| Early approval gap | {e.EarlyApprovalGap.ToString("+0.000;-0.000", inv)} | |");
        sb.AppendLine();

        if (e.HasEventStudy)
        {
            sb.AppendLine("## Event study (shock)");
            sb.AppendLine();
            sb.AppendLine("| Window | Mean Alpha net mig | Mean push | Mean approval | DID growth |");
            sb.AppendLine("|--------|-------------------|-----------|---------------|------------|");
            sb.AppendLine(
                $"| Pre-shock (M1-M{study.ShockMonth}) | {e.PreShockMeanNetMig.ToString("0", inv)} | " +
                $"{e.PreShockMeanPush.ToString("0.00", inv)} | {e.PreShockMeanApproval.ToString("0.00", inv)} | " +
                $"{e.PreShockDidGrowth.ToString("+0.0%;-0.0%", inv)} |");
            sb.AppendLine(
                $"| Post-shock (+{ScientificEvaluator.PostShockWindow}m) | {e.PostShockMeanNetMig.ToString("0", inv)} | " +
                $"{e.PostShockMeanPush.ToString("0.00", inv)} | {e.PostShockMeanApproval.ToString("0.00", inv)} | - |");
            sb.AppendLine();
        }

        if (battery.DoseCurve.Count > 0)
        {
            sb.AppendLine("## Dose-response");
            sb.AppendLine();
            sb.AppendLine("| Alpha tax | ATT pop % | ATT mean push | DID growth | ATT cum tax | ATT mean prod |");
            sb.AppendLine("|-----------|-----------|---------------|------------|-------------|---------------|");
            foreach (var d in battery.DoseCurve)
            {
                sb.AppendLine(
                    $"| {d.Tax.ToString("0.00", inv)} | {Pct(d.AttPopPct)} | " +
                    $"{d.AttMeanPush.ToString("+0.000;-0.000;0.000", inv)} | {Pct(d.DidPopGrowth)} | " +
                    $"{d.AttTaxRevenue.ToString("+0.0;-0.0;0.0", inv)} | {d.AttMeanProd.ToString("+0.00;-0.00;0.00", inv)} |");
            }

            sb.AppendLine();
            sb.AppendLine(
                $"- Monotonic (more tax -> more negative ATT): **{agg.DoseMonotonic}**");
            sb.AppendLine(
                $"- First tax with ATT pop % <= -5%: **{(agg.TaxAtAttMinus5Pct?.ToString("0.00", inv) ?? "n/a")}**");
            sb.AppendLine(
                $"- First tax with ATT pop % <= -20%: **{(agg.TaxAtAttMinus20Pct?.ToString("0.00", inv) ?? "n/a")}**");
            sb.AppendLine();
        }

        if (battery.Placebo is { } placebo)
        {
            sb.AppendLine("## Placebo high twin");
            sb.AppendLine();
            sb.AppendLine("| Estimand | Placebo (Alpha=Beta=high) | Primary |");
            sb.AppendLine("|----------|---------------------------|---------|");
            sb.AppendLine(
                $"| DID pop growth | {Pct(placebo.Result.Effects.DidPopGrowth)} | " +
                $"{Pct(agg.PrimaryDid)} |");
            sb.AppendLine(
                $"| Alpha pop delta | {placebo.Result.Effects.AlphaPopDelta.ToString("+0;-0", inv)} | " +
                $"{e.AlphaPopDelta.ToString("+0;-0", inv)} |");
            sb.AppendLine(
                $"| Beta pop delta | {placebo.Result.Effects.BetaPopDelta.ToString("+0;-0", inv)} | " +
                $"{e.BetaPopDelta.ToString("+0;-0", inv)} |");
            sb.AppendLine(
                $"| Gamma absorb | {placebo.Result.Effects.GammaAbsorbShare.ToString("0.0%", inv)} | " +
                $"{e.GammaAbsorbShare.ToString("0.0%", inv)} |");
            sb.AppendLine();
            sb.AppendLine(
                "Expect placebo |DID| << primary |DID| (both polities high-tax; twin contrast collapses).");
            sb.AppendLine();
        }

        if (battery.Ensemble.Count > 0)
        {
            sb.AppendLine("## Seed ensemble");
            sb.AppendLine();
            sb.AppendLine("| Seed | ATT pop % | DID growth | ATT mean push |");
            sb.AppendLine("|------|-----------|------------|---------------|");
            foreach (var p in battery.Ensemble)
            {
                sb.AppendLine(
                    $"| {p.Seed} | {Pct(p.AttPopPct)} | " +
                    $"{Pct(p.DidPopGrowth)} | " +
                    $"{p.AttMeanPush.ToString("+0.000;-0.000;0.000", inv)} |");
            }

            sb.AppendLine();
            sb.AppendLine(
                $"- Mean / min / max ATT%: **{Pct(agg.EnsembleMeanAttPct)}** / " +
                $"{Pct(agg.EnsembleMinAttPct)} / " +
                $"{Pct(agg.EnsembleMaxAttPct)}");
            sb.AppendLine($"- Same sign: **{agg.EnsembleSameSign}**");
            sb.AppendLine();
        }

        sb.AppendLine("## Interpretation guide");
        sb.AppendLine();
        sb.AppendLine("- **ATT primary** is the causal claim vs CF.");
        sb.AppendLine("- **Pre-trend** should be near zero under shock design (matched taxes pre-shock).");
        sb.AppendLine("- **Dose responds** shows the policy surface around the Economy tax-push threshold (~0.28).");
        sb.AppendLine("- **Placebo symmetry** fails if Gamma gravity alone drives twin DID.");
        sb.AppendLine("- **Fiscal tradeoff** flags revenue up while population falls under high tax.");
        sb.AppendLine("- **Ensemble sign** is robustness across seeds, not statistical inference.");
        sb.AppendLine();

        AppendSeries(sb, months, inv);
        sb.AppendLine("---");
        sb.AppendLine("*Generated by MobilityLab science battery - paste this block into chat for review.*");
        return sb.ToString();
    }

    static void AppendSpec(
        StringBuilder sb, ExperimentSpec spec, int samples, TimeSpan? elapsed, CultureInfo inv)
    {
        sb.AppendLine("## Spec");
        sb.AppendLine();
        sb.AppendLine("| Parameter | Value |");
        sb.AppendLine("|-----------|-------|");
        sb.AppendLine($"| Alpha tax (treatment) | {spec.AlphaTax.ToString("0.00", inv)} |");
        sb.AppendLine($"| Beta tax (control) | {spec.BetaTax.ToString("0.00", inv)} |");
        sb.AppendLine($"| Gamma tax (haven) | {spec.GammaTax.ToString("0.00", inv)} |");
        sb.AppendLine($"| Months | {samples} / {spec.Months} |");
        sb.AppendLine($"| Shock month | {spec.ShockMonth} |");
        sb.AppendLine($"| Seed | {spec.Seed} |");
        if (elapsed is { } t)
            sb.AppendLine($"| Elapsed | {t.TotalSeconds.ToString("0.00", inv)}s |");
        sb.AppendLine();
    }

    static void AppendSeries(StringBuilder sb, IReadOnlyList<MonthSample> months, CultureInfo inv)
    {
        sb.AppendLine("## Series snapshot (primary, every 6th month)");
        sb.AppendLine();
        sb.AppendLine("| M | Alpha pop | Beta pop | Gamma pop | Alpha push | Beta push | Alpha App | Alpha tax |");
        sb.AppendLine("|---|-----------|----------|-----------|------------|-----------|-----------|-----------|");
        for (var i = 0; i < months.Count; i++)
        {
            if (i != 0 && (i + 1) % 6 != 0 && i != months.Count - 1)
                continue;
            var m = months[i];
            sb.AppendLine(
                $"| {m.Month} | {m.Alpha.Population.ToString("0", inv)} | " +
                $"{m.Beta.Population.ToString("0", inv)} | {m.Gamma.Population.ToString("0", inv)} | " +
                $"{m.Alpha.EmigrationPressure.ToString("0.00", inv)} | " +
                $"{m.Beta.EmigrationPressure.ToString("0.00", inv)} | " +
                $"{m.Alpha.Approval.ToString("0.00", inv)} | " +
                $"{m.Alpha.HouseholdTaxRate.ToString("0.00", inv)} |");
        }

        sb.AppendLine();
    }

    static string Ascii(string text) =>
        text.Replace("α", "Alpha", StringComparison.Ordinal)
            .Replace("β", "Beta", StringComparison.Ordinal)
            .Replace("γ", "Gamma", StringComparison.Ordinal)
            .Replace("→", "->", StringComparison.Ordinal)
            .Replace("Σ", "sum", StringComparison.Ordinal)
            .Replace("≥", ">=", StringComparison.Ordinal)
            .Replace("–", "-", StringComparison.Ordinal)
            .Replace("—", "-", StringComparison.Ordinal);

    static string Pct(double v) =>
        v.ToString("+0.0%;-0.0%;0.0%", CultureInfo.InvariantCulture);
}
